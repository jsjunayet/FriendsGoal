import { NextResponse } from "next/server";
import crypto from "crypto";

export async function GET(request: Request) {
  try {
    const { searchParams } = new URL(request.url);
    const folder = searchParams.get("folder") || "friends_goal";

    // 1. Try forwarding to backend first
    const backendBase =
      process.env.NEXT_PUBLIC_API_URL?.replace(/\/$/, "") ||
      "http://localhost:5000/api/v1";

    try {
      const backendRes = await fetch(`${backendBase}/upload/signature?folder=${encodeURIComponent(folder)}`, {
        cache: "no-store",
      });
      if (backendRes.ok) {
        const json = await backendRes.json();
        if (json.success && json.data) {
          return NextResponse.json(json);
        }
      }
    } catch (_) {
      // Backend not directly reachable from serverless, fall through to local computation
    }

    // 2. Compute signature locally using standard crypto and env vars (or fallback dev credentials)
    const cloudName =
      process.env.NEXT_PUBLIC_CLOUDINARY_CLOUD_NAME ||
      process.env.CLOUDINARY_CLOUD_NAME ||
      "dzxzxdsnq";
    const apiKey =
      process.env.NEXT_PUBLIC_CLOUDINARY_API_KEY ||
      process.env.CLOUDINARY_API_KEY ||
      "347973325524831";
    const apiSecret =
      process.env.CLOUDINARY_API_SECRET || "oVX0wOsaxLNjEsFG0b7at_kOM6U";

    const timestamp = Math.round(new Date().getTime() / 1000);
    // Cloudinary signature parameter string (sorted alphabetically: folder, timestamp)
    const paramString = `folder=${folder}&timestamp=${timestamp}${apiSecret}`;
    const signature = crypto.createHash("sha1").update(paramString).digest("hex");

    return NextResponse.json({
      success: true,
      message: "Signature generated by Next.js serverless route",
      data: {
        signature,
        timestamp,
        apiKey,
        cloudName,
        folder,
      },
    });
  } catch (error: any) {
    return NextResponse.json(
      {
        success: false,
        message: error.message || "Failed to generate upload signature",
      },
      { status: 500 }
    );
  }
}

export async function POST(request: Request) {
  return GET(request);
}
